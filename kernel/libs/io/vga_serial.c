void vga_set_scale(int scale) {
    if (scale < 1) scale = 1;
    g_vga_scale = scale;
}

void draw_char_pixel(char c, int px, int py, uint32_t fg, uint32_t bg) {
    if (!global_fb || (uint8_t)c >= 128) return;
    const uint8_t* glyph = font8x8_basic[(uint8_t)c];
    for (int i = 0; i < 8; i++) {
        for (int j = 0; j < 8; j++) {
            uint32_t color = (glyph[i] & (1 << (7 - j))) ? fg : bg;
            for (int sy = 0; sy < g_vga_scale; sy++) {
                for (int sx = 0; sx < g_vga_scale; sx++) {
                    draw_pixel(px + j * g_vga_scale + sx, py + i * g_vga_scale + sy, color);
                }
            }
        }
    }
}

void vga_write_char(char c, uint8_t color_attr) {
    if (c == '\b') {
        serial_write_char('\b'); serial_write_char(' '); serial_write_char('\b');
    } else {
        serial_write_char(c);
    }

    if (g_vga_silent) return;
    if ((uint8_t)c < 32 && c != '\n' && c != '\r' && c != '\b' && c != '\t') return;
    if (!global_fb) return;

    int char_width = 8 * g_vga_scale;
    int max_cols = global_fb->width / char_width;
    uint32_t fg = vga_colors[color_attr & 0x0F];
    uint32_t bg = vga_colors[(color_attr >> 4) & 0x0F];

    if (c == '\n') { cursor_x = 0; cursor_y++; }
    else if (c == '\r') { cursor_x = 0; }
    else if (c == '\b') {
        if (cursor_x > 0) cursor_x--;
        draw_char_pixel(' ', cursor_x * char_width, cursor_y * 8 * g_vga_scale, fg, bg);
    } else {
        if (cursor_x >= max_cols) { cursor_x = 0; cursor_y++; }
        draw_char_pixel(c, cursor_x * char_width, cursor_y * 8 * g_vga_scale, fg, bg);
        if (cursor_y < TERM_ROWS && cursor_x < TERM_COLS) {
            terminal_buffer[cursor_y][cursor_x] = c;
            terminal_attr[cursor_y][cursor_x] = color_attr;
        }
        cursor_x++;
    }

    int char_height = 8 * g_vga_scale;
    int max_rows = (global_fb->height / char_height) - 1;
    if (max_rows > TERM_ROWS - 1) max_rows = TERM_ROWS - 1;

    if (cursor_y >= max_rows) {
        for (int row = 0; row < max_rows - 1; row++) {
            for (int col = 0; col < TERM_COLS; col++) {
                terminal_buffer[row][col] = terminal_buffer[row + 1][col];
                terminal_attr[row][col] = terminal_attr[row + 1][col];
            }
        }
        for (int col = 0; col < TERM_COLS; col++) {
            terminal_buffer[max_rows - 1][col] = ' ';
            terminal_attr[max_rows - 1][col] = 0x07;
        }
        uint32_t* fb_ptr = (uint32_t*)global_fb->address;
        size_t row_pixels = global_fb->pitch / 4;
        size_t scroll_size = (max_rows - 1) * char_height * row_pixels;
        size_t offset = char_height * row_pixels;
        for (size_t i = 0; i < scroll_size; i++) fb_ptr[i] = fb_ptr[i + offset];
        size_t bottom_start = (max_rows - 1) * char_height * row_pixels;
        for (size_t i = 0; i < char_height * row_pixels; i++) fb_ptr[bottom_start + i] = 0;
        cursor_y = max_rows - 1;
    }
}

void vga_clear(void) {
    if (!global_fb) return;
    for (uint64_t i = 0; i < global_fb->height * global_fb->pitch / 4; i++)
        ((uint32_t*)global_fb->address)[i] = 0;
    cursor_x = 0; cursor_y = 0;
    for (int r = 0; r < TERM_ROWS; r++) {
        for (int c = 0; c < TERM_COLS; c++) {
            terminal_buffer[r][c] = ' ';
            terminal_attr[r][c] = 0x07;
        }
    }
}

