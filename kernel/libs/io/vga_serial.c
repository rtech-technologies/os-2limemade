void vga_serial_service(kernel_event_t event) {
    if (event == EVENT_INIT) {
        serial_init();
        struct limine_framebuffer_response* fb_resp = get_framebuffer();
        if (fb_resp && fb_resp->framebuffer_count > 0) global_fb = fb_resp->framebuffers[0];
        vga_clear();
    }
}

void vga_sync_logs(void) {
    #include <include/vfs.h>
    for (int r = 0; r < TERM_ROWS; r++) {
        char line[81]; int last_char = -1;
        for (int c = 0; c < TERM_COLS; c++) {
            line[c] = terminal_buffer[r][c];
            if (line[c] != ' ') last_char = c;
        }
        if (last_char != -1) {
            line[last_char + 1] = '\n'; line[last_char + 2] = '\0';
            vfs_sync_boot_log(line);
        }
    }
}
