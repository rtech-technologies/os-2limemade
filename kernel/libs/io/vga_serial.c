static inline void outb(uint16_t port, uint8_t val) {
    __asm__ volatile ("outb %0, %1" : : "a"(val), "Nd"(port));
}

static inline uint8_t inb(uint16_t port) {
    uint8_t ret;
    __asm__ volatile ("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

#define SERIAL_PORT CONFIG_SERIAL_PORT

void serial_init(void) {
    outb(SERIAL_PORT + 1, 0x00);
    outb(SERIAL_PORT + 3, 0x80);
    outb(SERIAL_PORT + 0, 0x03);
    outb(SERIAL_PORT + 1, 0x00);
    outb(SERIAL_PORT + 3, 0x03);
    outb(SERIAL_PORT + 2, 0xC7);
    outb(SERIAL_PORT + 4, 0x0B);
}

static int is_transmit_empty(void) {
    return inb(SERIAL_PORT + 5) & 0x20;
}

void serial_write_char(char c) {
    uint32_t timeout = 1000000;
    while (is_transmit_empty() == 0 && timeout--) {
        __asm__ volatile ("pause");
    }
    if (timeout > 0) outb(SERIAL_PORT, c);
}

void serial_write_str(const char* s) {
    for (int i = 0; s[i] != '\0'; i++) {
        serial_write_char(s[i]);
    }
}

int serial_received(void) { return inb(SERIAL_PORT + 5) & 1; }
char serial_read_char(void) {
    uint32_t timeout = 1000000;
    while (serial_received() == 0 && timeout--) { __asm__ volatile ("pause"); }
    if (timeout <= 0) return 0;
    return inb(SERIAL_PORT);
}

