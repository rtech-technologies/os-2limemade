int g_vga_scale = 2;
#define TERM_COLS 80
#define TERM_ROWS 40
char terminal_buffer[TERM_ROWS][TERM_COLS];
uint8_t terminal_attr[TERM_ROWS][TERM_COLS];

static struct limine_framebuffer* global_fb = NULL;

void draw_pixel(int x, int y, uint32_t color) {
    if (!global_fb) return;
    if (x < 0 || (uint64_t)x >= global_fb->width || y < 0 || (uint64_t)y >= global_fb->height) return;
    uint32_t* pixel = (uint32_t*)(global_fb->address + y * global_fb->pitch + x * 4);
    *pixel = color;
}

uint32_t get_pixel(int x, int y) {
    if (!global_fb) return 0;
    if (x < 0 || (uint64_t)x >= global_fb->width || y < 0 || (uint64_t)y >= global_fb->height) return 0;
    uint32_t* pixel = (uint32_t*)(global_fb->address + y * global_fb->pitch + x * 4);
    return *pixel;
}

