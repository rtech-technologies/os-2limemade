void gui_draw_rect(rsl_fb_t* fb, int x, int y, int w, int h, uint32_t color) {
    if (!fb || !fb->address) return;
    for (int i = 0; i < h; i++) {
        for (int j = 0; j < w; j++) {
            int px = x + j;
            int py = y + i;
            if (px >= 0 && (uint64_t)px < fb->width && py >= 0 && (uint64_t)py < fb->height) {
                uint32_t* pixel = (uint32_t*)(fb->address + py * fb->pitch + px * 4);
                *pixel = color;
            }
        }
    }
}

